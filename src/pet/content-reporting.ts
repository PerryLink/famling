export function emptyContentReportDraft(): ContentReportDraft {
  return {
    category: '',
    reporter_contact: '',
    relationship: '',
    target: '',
    target_version: '',
    evidence: '',
    requested_action: '',
    good_faith: false,
    share_with_respondent: false,
  }
}

function categoryById(id: ContentReportCategoryId | ''): ContentReportCategory | null {
  return CONTENT_REPORT_CATEGORIES.find((category) => category.id === id) ?? null
}

/** Fields that are needed before submitting a useful report (good faith included). */
export function missingContentReportFields(draft: ContentReportDraft): string[] {
  const missing: string[] = []
  if (!categoryById(draft.category)) missing.push('category')
  if (!draft.reporter_contact.trim()) missing.push('reporter_contact')
  if (!draft.target.trim()) missing.push('target')
  if (!draft.evidence.trim()) missing.push('evidence')
  if (!draft.requested_action.trim()) missing.push('requested_action')
  if (!draft.good_faith) missing.push('good_faith')
  return missing
}

function placeholder(value: string, fallback: string): string {
  const text = value.trim()
  return text === '' ? fallback : text
}

