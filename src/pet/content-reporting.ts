export interface ContentReportPanelDeps {
  readonly document: Document
  /** Test seam; production uses the global window. */
  readonly window?: ContentReportWindowSeam | null
  /** Test seam; production uses navigator.clipboard when available. */
  readonly clipboard?: ContentReportClipboard | null
  /** Test seam; production opens a new tab only on this explicit click. */
  readonly openExternal?: (url: string) => boolean
  /** Test seam; production downloads the JSON locally. */
  readonly downloadJson?: (filename: string, json: string) => void
  /** Injected clock for the exported generatedAt. */
  readonly now?: () => number
}

export interface ContentReportPanel {
  readonly root: HTMLElement
  open(): void
  close(): void
  isOpen(): boolean
}

function makeElement<K extends keyof HTMLElementTagNameMap>(
  doc: Document,
  tag: K,
  className?: string,
  text?: string,
): HTMLElementTagNameMap[K] {
  const element = doc.createElement(tag)
  if (className) element.className = className
  if (text !== undefined) element.textContent = text
  return element
}

function defaultDownloadJson(doc: Document, filename: string, json: string): void {
  const blob = new Blob([json], { type: 'application/json' })
  const url = URL.createObjectURL(blob)
  const link = doc.createElement('a')
  link.href = url
  link.download = filename
  link.click()
  URL.revokeObjectURL(url)
}

function defaultClipboard(): ContentReportClipboard | null {
  try {
    const clipboard = typeof navigator === 'undefined' ? null : navigator.clipboard
    if (clipboard && typeof clipboard.writeText === 'function') {
      return { writeText: (text: string) => clipboard.writeText(text) }
    }
  } catch {
    /* clipboard can be unavailable without a secure context */
  }
  return null
}

function defaultOpenExternal(deps: ContentReportPanelDeps): (url: string) => boolean {
  if (deps.openExternal) return deps.openExternal
  return (url: string): boolean => {
    const seam = deps.window ?? (typeof window === 'undefined' ? null : window)
    if (!seam || typeof seam.open !== 'function') return false
    try {
      return seam.open(url, '_blank', 'noopener,noreferrer') !== null
    } catch {
      return false
    }
  }
}

