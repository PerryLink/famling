export interface ContentReportJsonOptions {
  /** Injected clock so tests can assert a deterministic generatedAt. */
  readonly now?: () => number
}

/**
 * Local JSON export. Only the user-typed report fields plus static schema/channel
 * metadata are included; no device id, save data, logs or app state is read.
 */
export function buildContentReportJson(draft: ContentReportDraft, options: ContentReportJsonOptions = {}): string {
  const now = options.now?.() ?? Date.now()
  const category = categoryById(draft.category)
  const report: Record<string, string | boolean | null> = {
    category: category ? category.id : null,
    reporter_contact: draft.reporter_contact.trim(),
    relationship: draft.relationship.trim(),
    target: draft.target.trim(),
    target_version: draft.target_version.trim(),
    evidence: draft.evidence.trim(),
    requested_action: draft.requested_action.trim(),
    good_faith: draft.good_faith,
    share_with_respondent: draft.share_with_respondent,
  }
  return `${JSON.stringify(
    {
      schema: CONTENT_REPORT_SCHEMA,
      generatedAt: new Date(now).toISOString(),
      localOnly: true,
      uploaded: false,
      note: '本文件在本机生成；应用不会自动上传、联网或收集数据。',
      report,
      evidence_checklist: CONTENT_REPORT_EVIDENCE_ITEMS,
      channels: {
        email_for_private_material: CONTENT_REPORT_EMAIL,
        public_issue_form: CONTENT_REPORT_ISSUE_URL,
        process_document: CONTENT_REPORT_DOC_PATH,
        emergency: ['110/120', '12377', '12356'],
      },
    },
    null,
    2,
  )}\n`
}

