/**
 * In-app content reporting / takedown / counter-notice entry (E12 MB-121).
 *
 * The app must offer a working reporting entry WITHOUT becoming a data
 * collector or a background uploader. This module therefore:
 *   - builds a copyable report template and a local JSON export from fields the
 *     user typed (nothing is read from the save file, account, device or logs);
 *   - never calls fetch/XMLHttpRequest/sendBeacon and never persists the draft;
 *   - opens the public GitHub issue form (or copies its URL) only on an explicit
 *     click;
 *   - explains scope, evidence, human handling (best effort, not automatic) and
 *     counter-notice in the dialog and in docs/legal/CONTENT-REPORTING.md.
 *
 * The issue form lives at .github/ISSUE_TEMPLATE/content-report.yml; the field
 * ids below are the single source shared by the template builder, the dialog and
 * the tests that keep the YAML form in sync.
 */

